"""Report generation for the prototype-based AD decision-support framework.

Pipeline: for each subject, retrieve relevant PubMed abstracts from a local FAISS
index by dense similarity search, filter and diversify the candidates, and prompt
a commercial LLM to write a patient-specific risk explanation with inline PMID
citations. Cited-reference metadata (authors, title, journal, year) is resolved
from PubMed identifiers via the NCBI E-utilities esummary endpoint rather than
being generated by the model.

Credentials and input paths are passed on the command line (or via environment
variables; nothing is hard-coded in this package):
  python prototype_rag.py --api-key sk-... --test-csv external_features.csv \
      --test-json <model inference JSON> --prototype-json <prototypes JSON> \
      --importance-json <feature importance JSON> --features-range-csv <ranges CSV>
  # or: export OPENAI_API_KEY="sk-..."   export OPENAI_API_BASE="https://api.openai.com/v1"
"""
import os
import json
import re
import urllib.request
import pandas as pd
from langchain_community.vectorstores import FAISS
from langchain_openai import OpenAIEmbeddings
from langchain_core.messages import HumanMessage, SystemMessage
from langchain.chat_models import init_chat_model
from tenacity import retry, stop_after_attempt, wait_exponential

os.environ["OPENAI_API_KEY"] = os.environ.get("OPENAI_API_KEY", "")
os.environ["OPENAI_API_BASE"] = os.environ.get("OPENAI_API_BASE", "")

PUBMED_ESUMMARY_URL = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esummary.fcgi"
_pubmed_meta_cache = {}


@retry(stop=stop_after_attempt(3), wait=wait_exponential(min=1, max=10))
def get_embeddings(text, embeddings_model):
    embedding = embeddings_model.embed_query(text)
    if not embedding or not isinstance(embedding, list):
        raise ValueError("Invalid embedding")
    return embedding


def extract_value(text, keyword):
    pattern = rf"{re.escape(keyword)}\s*(is|:)?\s*([-+]?[0-9]*\.?[0-9]+)"
    match = re.search(pattern, text, re.IGNORECASE)
    if match:
        return match.group(2)
    return "N/A"


def format_number(value):
    """Format a numeric value for display.

    - values in [1e-5, 0.01) are rendered in scientific notation (x.xx * 10^(-e))
    - values >= 0.01 are rounded to two decimals
    - avoids misleading "0.00" output
    """
    try:
        num = float(value)
        if num == 0:
            return "0.00"

        if 1e-5 <= abs(num) < 0.01:
            sci_str = f"{num:.4e}"
            coeff, exp = sci_str.split('e')
            exp = int(exp)
            coeff_rounded = f"{float(coeff):.2f}"
            return f"{coeff_rounded} * 10^({exp})"

        return f"{num:.2f}"
    except (ValueError, TypeError):
        return "N/A"


def compute_severity_score(class_probs):
    """Disease severity = sum_c c * P(y=c) over HC=0, MCI=1, AD=2.

    Accepts a dict whose keys are 'HC'/'MCI'/'AD' or 0/1/2 (any casing).
    """
    if not class_probs:
        return None
    mapping = {"hc": 0, "mci": 1, "ad": 2, "0": 0, "1": 1, "2": 2, 0: 0, 1: 1, 2: 2}
    p = [0.0, 0.0, 0.0]
    found = False
    for k, v in class_probs.items():
        key = str(k).strip().lower() if isinstance(k, str) else k
        if key in mapping:
            p[mapping[key]] = float(v)
            found = True
    if not found and len(class_probs) == 3:
        # Fallback: assume values are already ordered as [P(HC), P(MCI), P(AD)]
        try:
            p = [float(x) for x in class_probs.values()]
            found = True
        except (ValueError, TypeError):
            found = False
    if not found:
        return None
    return float(p[0] * 0 + p[1] * 1 + p[2] * 2)


def fetch_pubmed_metadata(pmids, timeout=15):
    """Resolve PMIDs to bibliographic metadata via NCBI E-utilities.

    Returns {pmid: {"pmid", "authors", "title", "journal", "year"}} for the
    identifiers that could be resolved. Results are cached in-memory. Any lookup
    that fails (network error or unknown PMID) is omitted from the result; the
    caller falls back to a PMID-only citation line.
    """
    ids = [str(p) for p in pmids if str(p) not in ("Unknown", "None", "", "nan")]
    out = {}
    missing = [i for i in ids if i not in _pubmed_meta_cache]
    if missing:
        url = PUBMED_ESUMMARY_URL + "?db=pubmed&retmode=json&id=" + ",".join(missing)
        try:
            with urllib.request.urlopen(url, timeout=timeout) as resp:
                payload = json.loads(resp.read().decode("utf-8"))
            for pmid in missing:
                rec = payload.get("result", {}).get(pmid)
                if not rec:
                    _pubmed_meta_cache[pmid] = None
                    continue
                authors = rec.get("authors", [])
                first_author = authors[0].get("name", "Unknown") if authors else "Unknown"
                pubdate = str(rec.get("pubdate", ""))
                year = re.search(r"\d{4}", pubdate).group(0) if re.search(r"\d{4}", pubdate) else "Unknown"
                _pubmed_meta_cache[pmid] = {
                    "pmid": pmid,
                    "authors": first_author,
                    "title": rec.get("title", "Unknown"),
                    "journal": rec.get("fulljournalname") or rec.get("source", "Unknown"),
                    "year": year,
                }
        except Exception:
            for pmid in missing:
                _pubmed_meta_cache[pmid] = None
    for i in ids:
        if _pubmed_meta_cache.get(i):
            out[i] = _pubmed_meta_cache[i]
    return out


def save_markdown(sample_id, content, output_dir):
    os.makedirs(output_dir, exist_ok=True)
    with open(os.path.join(output_dir, f"{sample_id}.md"), "w") as f:
        f.write(content)


def docs_by_modal_and_feature(docs_list, imaging_keywords, feature_keywords):
    """Return docs that match modality AND at least one feature keyword."""
    out = []
    for doc in docs_list:
        txt = (doc.page_content or "").lower()
        if any(k.lower() in txt for k in imaging_keywords) and any(fk in txt for fk in feature_keywords):
            out.append(doc)
    return out


def docs_by_modality_only(docs_list, imaging_keywords):
    """Return docs that match the imaging modality only."""
    out = []
    for doc in docs_list:
        txt = (doc.page_content or "").lower()
        if any(k.lower() in txt for k in imaging_keywords):
            out.append(doc)
    return out


def ensure_topk_with_fallback(vector_store, emb, imaging_keywords, feature_keywords, top_k=5, initial_k=20, max_expand_k=200):
    """Retrieve up to top_k candidate documents.

    Strategy:
    1) dense semantic search with k=initial_k
    2) prefer modality+feature matches, then modality-only matches, then raw hits
    3) if fewer than top_k candidates, double the search window up to max_expand_k
    4) return candidates ordered by metadata similarity when available
    """
    cur_k = initial_k
    tried_pmids = set()
    candidates = []

    while cur_k <= max_expand_k:
        docs_raw = vector_store.similarity_search_by_vector(emb, k=cur_k)

        docs_a = docs_by_modal_and_feature(docs_raw, imaging_keywords, feature_keywords)
        docs_b = docs_by_modality_only(docs_raw, imaging_keywords)
        docs_c = docs_raw

        # Merge while preserving order and avoiding duplicate PMIDs.
        merged = []
        for dset in (docs_a, docs_b, docs_c):
            for d in dset:
                pmid = d.metadata.get("pmid")
                if pmid in tried_pmids:
                    continue
                tried_pmids.add(pmid)
                merged.append(d)
                if len(merged) >= top_k:
                    break
            if len(merged) >= top_k:
                break

        if len(merged) >= top_k:
            candidates = merged[:top_k]
            break

        # Widen the search window and retry; accept the largest pool at the limit.
        cur_k = min(cur_k * 2, max_expand_k)
        if cur_k == max_expand_k:
            docs_raw = vector_store.similarity_search_by_vector(emb, k=cur_k)
            docs_a = docs_by_modal_and_feature(docs_raw, imaging_keywords, feature_keywords)
            docs_b = docs_by_modality_only(docs_raw, imaging_keywords)
            merged = []
            tried_pmids = set()
            for dset in (docs_a, docs_b, docs_raw):
                for d in dset:
                    pmid = d.metadata.get("pmid")
                    if pmid in tried_pmids:
                        continue
                    tried_pmids.add(pmid)
                    merged.append(d)
                    if len(merged) >= top_k:
                        break
                if len(merged) >= top_k:
                    break
            candidates = merged[:top_k]
            break

    if not candidates:
        candidates = docs_raw[:top_k] if docs_raw else []
    return candidates


# ---------------------------------------------------------------------------
# Citation diversity controller
# ---------------------------------------------------------------------------

citation_counter = {}  # {pmid: number of times used across reports}
MAX_REPEAT = 5
PRIORITY_THRESHOLD = 0.85


def select_diversified_from_candidates(candidates, top_k=5):
    """Pick up to top_k documents from an ordered candidate list.

    - high-similarity evidence (>= PRIORITY_THRESHOLD) bypasses the repeat limit
    - other documents are limited by MAX_REPEAT reuses across reports
    """
    selected = []
    for doc in candidates:
        pmid = doc.metadata.get("pmid")
        sim = float(doc.metadata.get("similarity", 0) or 0)

        if not pmid:
            pmid = f"Unknown-{id(doc)}"  # unique placeholder

        count = citation_counter.get(pmid, 0)
        if sim >= PRIORITY_THRESHOLD:
            selected.append(doc)
            citation_counter[pmid] = count + 1
        elif count < MAX_REPEAT:
            selected.append(doc)
            citation_counter[pmid] = count + 1

        if len(selected) >= top_k:
            break

    # Fallback: fill remaining slots with leftover candidates, ignoring the limit.
    if len(selected) < top_k and candidates:
        for doc in candidates:
            if doc in selected:
                continue
            selected.append(doc)
            if len(selected) >= top_k:
                break

    return selected[:top_k]


def normalize_pubmed_year(doc):
    """Extract a clean 4-digit publication year from metadata."""
    pmid = doc.metadata.get("pmid")
    year = doc.metadata.get("year")

    try:
        years = re.findall(r"\d{4}", str(year))
        if years:
            return int(max(years))
        return "Unknown"
    except Exception:
        return "Unknown"


def generate_markdown_reports(
    prototype_path,
    test_path,
    output_dir,
    importance_path,
    test_csv_path,
    features_range_path,
    top_k=5,
    wm_k=5
):
    with open(prototype_path, "r") as f:
        prototypes = json.load(f)
    with open(test_path, "r") as f:
        test_samples = json.load(f)
    with open(importance_path, "r") as f:
        importance = json.load(f)

    test_csv = pd.read_csv(test_csv_path)

    features_range = pd.read_csv(features_range_path, index_col=0)
    features_range = features_range.transpose()
    features_range.index.name = 'feature_name'
    features_range.reset_index(inplace=True)

    sorted_features = sorted(importance.items(), key=lambda x: x[1], reverse=True)
    wm_keywords = ["fractional_anisotropy", "fractional anisotropy", "mean_diffusivity", "mean diffusivity",
                   "axial_diffusivity", "axial diffusivity", "radial_diffusivity", "radial diffusivity"]
    white_matter_features = [item for item in sorted_features if any(k in item[0] for k in wm_keywords)][:wm_k]
    brain_volume_features = [item for item in sorted_features if ("Volume" in item[0] or "volume" in item[0])
                             and item not in white_matter_features][:top_k]
    if len(brain_volume_features) < top_k:
        other_features = [item for item in sorted_features if item not in white_matter_features and item not in brain_volume_features]
        brain_volume_features += other_features[:(top_k - len(brain_volume_features))]

    # Language model and embedding setup.
    llm = init_chat_model("gpt-5.6", model_provider="openai",
                          temperature=0.7, top_p=1.0, max_tokens=1024)
    embeddings = OpenAIEmbeddings(model="text-embedding-3-large")

    # The PubMed FAISS index is not distributed with the code (its abstracts are
    # copyright-protected). Build it from a local PubMed dump, or point the
    # PUBMED_FAISS_INDEX environment variable at the index location.
    faiss_index = os.environ.get("PUBMED_FAISS_INDEX", "pubmed_faiss_index_new")
    vector_store = FAISS.load_local(
        faiss_index,
        embeddings,
        allow_dangerous_deserialization=True
    )

    imaging_keywords = [
        "MRI", "magnetic resonance", "structural MRI", "T1-weighted", "hippocampal volume",
        "cortical thickness", "volume", "gray matter volume", "atrophy", "voxel-based morphometry", "VBM",
        "DTI", "DWI", "diffusion", "FA", "MD", "white matter", "tractography",
        "fiber", "fiber tract", "connectivity", "tract", "TBSS"]

    for sample in test_samples:
        sample_id = sample["subject_id"]
        desc = sample.get("features_description", "")
        risk_score = sample.get("risk_score")
        risk_level = "High" if risk_score and risk_score > 0.7 else "Moderate" if risk_score and risk_score > 0.4 else "Low"
        risk_score_str = f"{risk_score:.3f}" if risk_score is not None else "N/A"
        risk_text = f"{risk_score_str} ({risk_level})" if risk_score is not None else "Not applicable (Already diagnosed)"

        class_probs = sample.get("class_probabilities", {})
        severity_score = compute_severity_score(class_probs)
        severity_text = f"{severity_score:.3f} (0=HC, 1=MCI, 2=AD)" if severity_score is not None else "Not applicable"

        age = sample.get("age", extract_value(desc, "age") or "N/A")
        mmse = sample.get("MMSE", extract_value(desc, "MMSE") or "N/A")
        sex_row = test_csv[test_csv["subject"] == sample_id]
        sex = "Male" if not sex_row.empty and sex_row.iloc[0].get("male") == 1 else "Female" if not sex_row.empty else "N/A"

        brain_volume_lines = []
        for name, _ in brain_volume_features:
            value = extract_value(desc, name) or "N/A"
            formatted_value = format_number(value)
            feature_row = features_range[features_range['feature_name'] == name]
            if not feature_row.empty:
                avg = format_number(feature_row['avg'].values[0])
                p5 = format_number(feature_row['5th percentile'].values[0])
                p95 = format_number(feature_row['95th percentile'].values[0])
                brain_volume_lines.append(
                    f"- **{name}**: {formatted_value} (HC avg: {avg}, normal range: {p5}-{p95})"
                )
            else:
                brain_volume_lines.append(f"- **{name}**: {formatted_value} (No HC reference data)")

        white_matter_lines = []
        for name, _ in white_matter_features:
            value = extract_value(desc, name) or "N/A"
            formatted_value = format_number(value)
            feature_row = features_range[features_range['feature_name'] == name]
            if not feature_row.empty:
                avg = format_number(feature_row['avg'].values[0])
                p5 = format_number(feature_row['5th percentile'].values[0])
                p95 = format_number(feature_row['95th percentile'].values[0])
                white_matter_lines.append(
                    f"- **{name}**: {formatted_value} (HC avg: {avg}, normal range: {p5}-{p95})"
                )
            else:
                white_matter_lines.append(f"- **{name}**: {formatted_value} (No HC reference data)")

        proto_descs = []
        for proto in sample.get("closest_prototypes", [])[:1]:
            idx = proto.get("prototype_index")
            proto_descs.append(f"Prototype {idx} (class {proto.get('class')})")

        # Prototype distance modulates the retrieval breadth. A sample far from
        # its closest prototype is atypical, so the search window is widened and
        # differential-diagnosis semantics are added to the query. The distance
        # itself is never written into the generated report.
        proto_dist = None
        _closest = sample.get("closest_prototypes") or []
        if _closest:
            try:
                proto_dist = float(_closest[0].get("distance"))
            except (TypeError, ValueError):
                proto_dist = None
        retrieval_top_k, retrieval_initial_k = 5, 20
        atypical = False
        if proto_dist is not None:
            scale = min(2.0, 1.0 + proto_dist / 8.0)  # d=0 -> 1.0x, d>=8 -> 2.0x
            retrieval_top_k = int(round(5 * scale))
            retrieval_initial_k = int(round(20 * scale))
            atypical = proto_dist > 5.0

        # Literature retrieval.
        query = (
            f"Alzheimer's risk explanation. Age {age}, Sex {sex}, MMSE {mmse}. "
            f"Brain volume features: {', '.join(k for k, _ in brain_volume_features)}. "
            f"White matter features: {', '.join(k for k, _ in white_matter_features)}. "
            f"Prototypes: {' '.join(proto_descs)}. "
            + (f"Disease severity score: {severity_score:.3f} (0=HC, 1=MCI, 2=AD). " if severity_score is not None else "")
            + ("Atypical presentation; consider differential diagnosis and disease heterogeneity." if atypical else "")
        )
        try:
            emb = get_embeddings(query, embeddings)
            candidates = ensure_topk_with_fallback(
                vector_store=vector_store,
                emb=emb,
                imaging_keywords=imaging_keywords,
                feature_keywords=[k.lower() for k, _ in brain_volume_features] + [k.lower() for k, _ in white_matter_features],
                top_k=retrieval_top_k,
                initial_k=retrieval_initial_k,
                max_expand_k=200
            )

            candidates = sorted(candidates, key=lambda x: float(x.metadata.get("similarity", 0) or 0), reverse=True)
            docs = select_diversified_from_candidates(candidates, top_k=retrieval_top_k)

            cited_literature = []
            seen_pmids = set()
            for doc in docs:
                pmid = doc.metadata.get("pmid", "Unknown")
                if pmid in seen_pmids:
                    continue
                seen_pmids.add(pmid)
                year = normalize_pubmed_year(doc)
                cited_literature.append(f"PMID: {pmid}, year: {year}")
        except Exception:
            cited_literature = []
            docs = []

        # Resolve cited-reference metadata from PubMed (not generated by the LLM).
        cited_lines = []
        resolved = fetch_pubmed_metadata([d.metadata.get("pmid") for d in docs])
        for i, doc in enumerate(docs, 1):
            pmid = str(doc.metadata.get("pmid", "Unknown"))
            meta = resolved.get(pmid)
            if meta:
                cited_lines.append(
                    f"{i}. {meta['authors']}, et al. {meta['title']}. {meta['journal']}. {meta['year']}. PMID: {pmid}"
                )
            else:
                cited_lines.append(f"{i}. PMID: {pmid}")

        # Report generation. The model writes the two-paragraph explanation and
        # cites literature inline as (PMID: XXXX); it does not produce citations.
        messages = [
            SystemMessage(content=(
                "You are a practicing neurologist. Use the patient-specific data and the retrieved PubMed "
                "literature to explain this individual's Alzheimer's risk. You MUST cite literature inline "
                "as (PMID: XXXX) where XXXX exactly matches one of the retrieved PMIDs. Do not invent PMIDs."
            )),
            HumanMessage(content=f"Patient info: Age {age}, Sex {sex}, MMSE {mmse}."),
            HumanMessage(content="Volume and Cortical Top 5 Features:\n" + "\n".join(brain_volume_lines)),
            HumanMessage(content="White Matter Microstructure Top 5 Features:\n" + "\n".join(white_matter_lines)),
            HumanMessage(content=("Closest Prototype:\n" + "\n".join(proto_descs)) if proto_descs else "Closest Prototype: not available"),
            HumanMessage(content=(f"Disease severity score (0=HC, 1=MCI, 2=AD): {severity_score:.3f}") if severity_score is not None else "Disease severity score: not available"),
            HumanMessage(content=(
                "Retrieved PubMed literature (use ONLY these PMIDs for inline citations):\n"
                + "\n".join([
                    f"- PMID: {doc.metadata.get('pmid', 'Unknown')}"
                    f" | excerpt: {doc.page_content[:500]}"
                    for doc in docs
                ])
            )),
            HumanMessage(content=(
                "Write a detailed explanation citing the papers above using (PMID: XXXX). "
                "Write one paragraph analyzing the impact of Volume and Cortical changes, "
                "and a separate paragraph analyzing the impact of White Matter Microstructure changes. "
                "End directly after the two paragraphs; do not diverge to new questions."
            )),
        ]
        try:
            response = llm.invoke(messages)
            explanation = response.content.strip()
        except Exception as e:
            explanation = f"Explanation generation failed: {e}"

        markdown = f"""# Alzheimer's Risk Report of {sample_id}

## Patient Information
- **Age**: {age}
- **Sex**: {sex}
- **MMSE**: {mmse}
- **Risk Score**: {risk_text}
- **Disease Severity Score**: {severity_text}

---

## Volume and Cortical Top 5 Features
{chr(10).join(brain_volume_lines)}

---

## White Matter Microstructure Top 5 Features
{chr(10).join(white_matter_lines)}

---

## Closest Prototype Explanations
{chr(10).join(proto_descs)}

---

## Risk Explanation with References
{explanation}

---

## Cited Literature
{chr(10).join(cited_lines) if cited_lines else (chr(10).join([f"- {lit}" for lit in cited_literature]) if cited_literature else 'No literature retrieved.')}

---

## Summary
- **Risk Level**: {risk_level if risk_score is not None else 'Already diagnosed'}
- **Recommendation**: Suggest follow-up assessment and longitudinal monitoring.
"""

        save_markdown(sample_id, markdown, output_dir)
        print(f"Saved report for {sample_id}")

    print(f"All reports saved to: {output_dir}")


def filter_and_diversify_docs(docs_raw, imaging_keywords, top_k=5):
    """Filter by imaging modality, sort by similarity, then diversify picks.

    1) modality filtering (respect imaging keywords)
    2) diversity control (avoid over-citing the same paper)
    3) strong-match exemption (>= PRIORITY_THRESHOLD bypasses the repeat limit)
    """
    imaging_docs = []
    for doc in docs_raw:
        text = doc.page_content.lower()
        if any(k.lower() in text for k in imaging_keywords):
            imaging_docs.append(doc)

    docs = imaging_docs if imaging_docs else docs_raw

    docs = sorted(docs, key=lambda x: x.metadata.get("similarity", 0), reverse=True)

    selected = []
    for doc in docs:
        pmid = doc.metadata.get("pmid")
        sim = doc.metadata.get("similarity", 0)
        if pmid is None:
            continue

        count = citation_counter.get(pmid, 0)

        # Strong match: bypass the repeat limit.
        if sim >= PRIORITY_THRESHOLD:
            selected.append(doc)
            citation_counter[pmid] = count + 1

        # Otherwise allow until the repeat limit is reached.
        elif count < MAX_REPEAT:
            selected.append(doc)
            citation_counter[pmid] = count + 1

        if len(selected) >= top_k:
            break

    return selected


